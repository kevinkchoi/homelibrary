/**
 * 사람이 **실제로 쓰는 대로** 알아듣도록 마크다운을 조금 눅여 준다.
 *
 * **왜 필요한가**: 마크다운 규칙은 `#` 뒤에 **반드시 한 칸**을 요구한다. 그런데 사람은
 * `#제목`이라고 붙여 쓴다. 규칙대로만 그리면 제목이 통째로 그냥 글자가 된다 —
 * 실제로 11,000자짜리 서평에서 제목 8개가 전부 날것으로 나왔다(2026-09-27 제보).
 * 글머리표도 마찬가지로 `**항목`, `*항목`처럼 적는데, 마크다운에서 그건 **굵게**의
 * 시작이라 닫는 표시가 없으면 `*`가 그대로 보인다.
 *
 * **저장된 글은 건드리지 않는다.** 그리는 순간에만 손본다 — 쓴 사람의 원문이
 * 조용히 바뀌는 일이 없어야 하고, 마음에 안 들면 그냥 고쳐 쓰면 된다.
 *
 * 규칙은 셋뿐이고, **진짜 마크다운은 절대 건드리지 않는다**:
 *   1. 줄머리 `#…#` 뒤에 칸이 없으면 넣어 준다 → 제목
 *   2. 줄머리 `*`/`**` 가 그 줄에서 **닫히지 않으면** 글머리표로 본다
 *      (닫히면 진짜 강조이므로 그대로 둔다)
 *   3. `***`, `---` 같은 구분선 줄은 손대지 않는다
 */

const HR = /^\s*([*\-_])\s*(?:\1\s*){2,}$/;

export function forgivingMarkdown(text) {
  if (!text) return text;

  return text
    .split("\n")
    .map((line) => {
      // 구분선(`***`, `---`, `___`)은 그대로 둔다 — 아래 규칙에 걸리면 깨진다.
      if (HR.test(line)) return line;

      // 1) `#제목` → `# 제목`
      const head = line.match(/^(#{1,6})(?=[^\s#])/);
      if (head) return `${head[1]} ${line.slice(head[1].length)}`;

      // 2) 줄머리 `*`/`**` 가 닫히지 않으면 글머리표로.
      const star = line.match(/^(\*{1,2})\s*(?=\S)/);
      if (star) {
        const marker = star[1];
        const rest = line.slice(star[0].length);
        // 같은 표시가 뒤에 또 나오면 **진짜 강조**다. 건드리지 않는다.
        if (!rest.includes(marker)) return `- ${rest}`;
      }

      return line;
    })
    .join("\n");
}
